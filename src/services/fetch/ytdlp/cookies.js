/**
 * Clearance cookie untuk yt-dlp.
 *
 * Saat situs yang dituju memasang proteksi (Cloudflare/DataDome/...),
 * yt-dlp biasa gagal karena tidak punya cookie clearance. Modul ini
 * menyelesaikan challenge lewat browser (lokal atau Scraping Browser remote),
 * lalu mengekspor cookie-nya ke format Netscape agar bisa dipakai
 * yt-dlp lewat flag `--cookies`.
 */

import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { stealthBrowser } from "@/src/utils/request/browser.js";
import { remoteBrowserAvailable, remoteSolveChallenge } from "@/src/services/network/scraping-browser.js";

const COOKIE_DIR = path.join(os.tmpdir(), "rizzerbot-ytdlp");

function browserDisabled() {
  return ["1", "true", "yes"].includes(String(process.env.BROWSER_DISABLED || "").toLowerCase());
}

/**
 * Ubah daftar cookie browser menjadi format Netscape (cookies.txt).
 * @param {Array<{name:string,value:string,domain?:string,path?:string,expires?:number,secure?:boolean}>} cookies
 * @returns {string}
 */
export function toNetscapeContent(cookies = []) {
  const lines = ["# Netscape HTTP Cookie File", "# Generated by rizzerbot", ""];
  for (const c of cookies) {
    if (!c?.name) continue;
    const domain = String(c.domain || "").replace(/^\./, "");
    const includeSub = String(c.domain || "").startsWith(".") ? "TRUE" : "FALSE";
    const secure = c.secure ? "TRUE" : "FALSE";
    const expires = Number(c.expires) > 0 ? Math.floor(Number(c.expires)) : 0;
    lines.push([domain, includeSub, c.path || "/", secure, expires, c.name, c.value ?? ""].join("\t"));
  }
  return lines.join("\n");
}

/**
 * Kumpulkan cookie clearance untuk sebuah URL.
 *
 * MenAttempt berurutan: browser stealth lokal -> Scraping Browser remote.
 * @returns {Promise<{file: string, source: string, cookies: object[]}|null>}
 */
export async function resolveClearanceCookies(url, { logger, timeoutMs = 25000 } = {}) {
  const cookies = [];

  if (!browserDisabled()) {
    try {
      const solved = await stealthBrowser.solveChallenge(url, { timeoutMs });
      if (Array.isArray(solved?.cookies)) cookies.push(...solved.cookies);
      if (!cookies.length) {
        logger?.warn?.("[ytdlp cookies] browser stealth tidak menghasilkan cookie clearance");
      }
    } catch (err) {
      logger?.warn?.(`[ytdlp cookies] browser stealth gagal: ${err?.message || err}`);
    }
  }

  let source = "browser";
  if (!cookies.length && remoteBrowserAvailable()) {
    try {
      const solved = await remoteSolveChallenge(url, { timeoutMs });
      if (Array.isArray(solved?.cookies)) cookies.push(...solved.cookies);
      source = "scraping-browser";
    } catch (err) {
      logger?.warn?.(`[ytdlp cookies] scraping browser gagal: ${err?.message || err}`);
    }
  }

  if (!cookies.length) return null;

  try {
    await fsp.mkdir(COOKIE_DIR, { recursive: true });
    const file = path.join(COOKIE_DIR, `cookies-${Date.now()}.txt`);
    await fsp.writeFile(file, toNetscapeContent(cookies), "utf8");
    return { file, source, cookies };
  } catch (err) {
    logger?.warn?.(`[ytdlp cookies] gagal menulis file cookie: ${err?.message || err}`);
    return null;
  }
}
